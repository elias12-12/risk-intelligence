def mk_txn(**kw):
    """Build a transactions row. Positional column lists are how the old
    generator introduced silent column-shift bugs; this makes that impossible."""
    unknown = set(kw) - set(TXN_COLS)
    if unknown:
        raise KeyError(f"unknown transaction column(s): {sorted(unknown)}")
    row = dict(_TXN_DEFAULTS, **kw)
    if row["amount_base"] is None:
        row["amount_base"] = row["amount"]
    return [row[c] for c in TXN_COLS]



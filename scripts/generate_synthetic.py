"""
Synthetic-data generator for the GlassBox risk prototype.

What it does
------------
1. Generates dimensions + ~7,700 background transactions over 30 days, so that
   baseline features (historical MCCs / countries, amount z-scores, card pace)
   are meaningful.
2. Plants five demo cases as RAW rows (transactions, events, links) only.
3. Adds a scored population: declines, refunds, a labelled fraud cohort, and a
   card-testing burst — so §10/§11 have something to measure and §14 has
   something to detect.
4. Emits everything as FK-safe INSERTs into fixtures/synthetic_data.sql.
5. Self-check: STRUCTURAL assertions about the rows it wrote.

What it deliberately does NOT do
--------------------------------
It does not write feature_values, and it does not compute scores.

The previous version derived 19 of 21 features in Python — counts, haversine,
z-scores, minutes-between-events — and wrote them straight to feature_values.
That is a second implementation of the feature layer, and §3.1's own argument
applies to it: if serving and training each implement a feature separately they
will diverge, and the divergence is invisible. The feature runner reading the
catalog is now the only implementation. Its agreement with the values this file
used to derive is pinned in tests/test_feature_runner.py.

The one exception is HAND_SEEDED_FEATURES below: new_payee_then_drain is a
sequence feature and the sequence runner is Week 3. One hand-seeded value out
of 21 is honest; nineteen was the situation this rewrite exists to end.

Deterministic (fixed seed) so the demo is stable. Pure standard library.
"""

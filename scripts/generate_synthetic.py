# ---------------------------------------------------------------- SQL helpers
def q(v):
    """Render a Python value as a SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, datetime):
        return "'" + v.astimezone(UTC).strftime("%Y-%m-%d %H:%M:%S.%f+00") + "'"
    return "'" + str(v).replace("'", "''") + "'"


class Emitter:
    def __init__(self):
        self.buf = []

    def comment(self, c):
        self.buf.append(f"\n-- {c}")

    def insert(self, table, cols, rows):
        if not rows:
            return
        CH = 500
        for i in range(0, len(rows), CH):
            chunk = rows[i:i + CH]
            self.buf.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES")
            self.buf.append(",\n".join("(" + ", ".join(q(x) for x in r) + ")" for r in chunk) + ";")

    def write(self, path):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write("-- Generated by scripts/generate_synthetic.py (seed=%d). Do not edit by hand.\n" % SEED)
            f.write("BEGIN;\n")
            f.write("\n".join(self.buf))
            f.write("\nCOMMIT;\n")


def haversine(lat1, lon1, lat2, lon2):
    R = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


